#!/usr/bin/env bash
# Regenerates builder/targets/*.env: the toolchain environment of each jssc target, taken from
# the dockcross image (pinned in builder/Containerfile) its toolchain is copied from.
# Run it after changing a digest in the Containerfile. Needs podman or docker.
set -euo pipefail
cd "$(dirname "$0")"
engine=${ENGINE:-$(command -v podman || command -v docker)}

# jssc target -> Containerfile stage
declare -A stages=(
    [linux_32]=linux-x86
    [linux_64]=linux-x64
    [linux_arm]=linux-armv6-lts
    [linux_arm64]=linux-arm64-lts
    [linux_riscv32]=linux-riscv32
    [linux_riscv64]=linux-riscv64
    [linux_ppc]=linux-ppc64le
    [windows_32]=windows-static-x86
    [windows_64]=windows-static-x64
    [windows_arm64]=windows-arm64
)

mkdir -p targets
for target in "${!stages[@]}"; do
    stage=${stages[$target]}
    image=$(awk -v s="$stage" '$1 == "FROM" && $3 == "AS" && $4 == s { print $2 }' Containerfile)
    [ -n "$image" ] || { echo "no stage $stage in Containerfile" >&2; exit 1; }
    "$engine" pull -q "$image" >/dev/null
    {
        echo "# Generated by gen-targets.sh from $image"
        "$engine" image inspect --format '{{range .Config.Env}}{{println .}}{{end}}' "$image" \
            | grep -v -E '^(TERM|LANG|LC_ALL|DEBIAN_FRONTEND|HOME)=' \
            | grep -v '^$' \
            | sed -E "s/^([^=]+)=(.*)$/\1='\2'/"
    } > "targets/$target.env"
done

# osxcross: deployment targets as before (10.9 for x86_64, 11.0 for arm64), both against SDK 11.3;
# clang is llvm-mingw's
for target in osx_64 osx_arm64; do
    case $target in
        osx_64) arch=x86_64 min=10.9 ;;
        osx_arm64) arch=arm64 min=11.0 ;;
    esac
    cat > "targets/$target.env" <<EOF
# Generated by gen-targets.sh (osxcross, see Containerfile)
PATH='/opt/osxcross/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin:/usr/xcc/aarch64-w64-mingw32-cross/bin'
OSXCROSS_TARGET_DIR='/opt/osxcross'
OSXCROSS_ARCH='$arch'
MACOSX_DEPLOYMENT_TARGET='$min'
EOF
done
ls targets
